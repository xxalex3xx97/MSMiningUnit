#!/usr/bin/env python3
"""gen_portdata_hpp.py: writes mods/MiningBenchMod/mb_portdata.hpp from bpu_port_data.lua.

Input: bpu_port_data.lua (generated by MSBlueprintUnit tooling/gen_port_order.py; read only).
Output: mb_portdata.hpp, one row per class: verified flag, cells (game byte order, rot 0, half cells, y down),
        site (website Ports Face/Index -> game index, -1 = site cell not in the game list).

Run: python -I scripts/gen_portdata_hpp.py [--lua path] [--out path]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEF_LUA = r"F:\MSBlueprintUnit\mods\BlueprintUnit\Scripts\bpu_port_data.lua"
DEF_OUT = os.path.normpath(os.path.join(HERE, "..", "mods", "MiningBenchMod", "mb_portdata.hpp"))
MAX_PORTS = 16

HEAD = re.compile(r'^\s*(DAT_\w+)\s*=\s*\{\s*verified = (true|false), cells = \{((?:\{-?\d+,-?\d+\},?)*)\}')
CELL = re.compile(r'\{(-?\d+),(-?\d+)\}')
SITE_BLOCK = re.compile(r'site = \{((?:\{face="\w",index=\d+,x=-?\d+,y=-?\d+\},?)*)\}')
SITE = re.compile(r'\{face="(\w)",index=(\d+),x=(-?\d+),y=(-?\d+)\}')


def parse(text):
    rows = []
    for line in text.splitlines():
        m = HEAD.match(line)
        if not m:
            continue
        name, verified, cells_txt = m.group(1), m.group(2) == "true", m.group(3)
        cells = [(int(x), int(y)) for x, y in CELL.findall(cells_txt)]
        if len(cells) > MAX_PORTS:
            raise SystemExit("too many ports for %s: %d" % (name, len(cells)))
        if len(set(cells)) != len(cells):
            raise SystemExit("duplicate cells for %s" % name)
        site = []
        sb = SITE_BLOCK.search(line)
        if sb:
            for face, idx, x, y in SITE.findall(sb.group(1)):
                game = cells.index((int(x), int(y))) if (int(x), int(y)) in cells else -1
                site.append((face, int(idx), game))
        if verified:
            if not site or any(g < 0 for _, _, g in site):
                raise SystemExit("verified class %s: site cells missing from game list" % name)
        rows.append((name, verified, cells, site))
    return rows


def emit(rows):
    out = [
        "// FILE: mods/MiningBenchMod/mb_portdata.hpp",
        "// GENERATED by scripts/gen_portdata_hpp.py from bpu_port_data.lua (MSBlueprintUnit tooling/gen_port_order.py). Do not edit.",
        "// WHAT: port table per machine DAT class, rot 0. cells = game port byte order (cell in half units, origin = machine centre, y down).",
        "//       site = website Ports (Face, Index) -> game byte index (-1 = not in the game list). verified = true only where a probe in game",
        "//       confirmed the order (Refinery, Assembler). Other classes are rule-derived: pp_site_flags never writes their port flags.",
        "struct PPortSite { char face; int index; int game; };",
        "struct PPortCls { const char* dat; bool verified; int n; int cells[16][2]; int ns; PPortSite site[16]; };",
        "const PPortCls kPortCls[] = {",
    ]
    for name, verified, cells, site in rows:
        c = ", ".join("{%d,%d}" % xy for xy in cells)
        s = ", ".join("{'%s',%d,%d}" % (f, i, g) for f, i, g in site)
        out.append('    { "%s", %s, %d, { %s }, %d, { %s } },' % (name, "true" if verified else "false", len(cells), c, len(site), s))
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lua", default=DEF_LUA)
    ap.add_argument("--out", default=DEF_OUT)
    a = ap.parse_args()
    with open(a.lua, encoding="utf-8") as f:
        rows = parse(f.read())
    if not any(v for _, v, _, _ in rows):
        raise SystemExit("no verified classes parsed")
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(emit(rows))
    print("wrote %s: %d classes, %d verified" % (a.out, len(rows), sum(1 for r in rows if r[1])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
